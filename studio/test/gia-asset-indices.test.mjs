// Independent observed identity fixture, not a production-schema roundtrip:
// probes/layers/beyond-export.gia, 7.1.0, SHA256
// 0f9334fbd97ba7dcfcab0aec76272aabef0707b1ad8b6ac74e1889d3dca67664.
// The user confirmed normal inspectors and individually created image assets.
// The successful original shop test changed ONLY 17 Info.index scalar bytes.
// Fixture indices are from that native file, not generated by the allocator.
const cat = (...buffers) => Buffer.concat(buffers)
function vi(value) {
  const bytes = []
  do { bytes.push((value % 128) | (value >= 128 ? 128 : 0)); value = Math.floor(value / 128) } while (value)
  return Buffer.from(bytes)
}
const msg = (field, bytes) => cat(vi(field * 8 + 2), vi(bytes.length), bytes)
const num = (field, value) => cat(vi(field * 8), vi(value))
const str = (field, text) => msg(field, Buffer.from(text))
function envelope(payload) {
  const head = Buffer.alloc(20), tail = Buffer.alloc(4)
  ;[payload.length + 20, 1, 0x326, 3, payload.length].forEach((value, i) => head.writeUInt32BE(value, i * 4))
  tail.writeUInt32BE(0x679)
  return cat(head, payload, tail)
}
function fields(bytes) {
  let offset = 0
  const read = () => {
    let result = 0, multiplier = 1, byte
    do { byte = bytes[offset++]; result += (byte & 127) * multiplier; multiplier *= 128 } while (byte & 128)
    return result
  }
  const result = []
  while (offset < bytes.length) {
    const start = offset, tag = read(), number = Math.floor(tag / 8), wire = tag & 7
    let value
    if (wire === 0) value = read()
    else {
      const length = wire === 2 ? read() : wire === 5 ? 4 : 8
      value = bytes.subarray(offset, offset + length)
      offset += length
    }
    result.push({ number, wire, value, raw: bytes.subarray(start, offset) })
  }
  return result
}
const all = (bytes, number) => fields(bytes).filter(row => row.number === number).map(row => row.value)
const first = (bytes, number) => all(bytes, number)[0] ?? Buffer.alloc(0)
function readIndices(buffer) {
  const payload = buffer.subarray(20, -4)
  return [...all(payload, 1), ...all(payload, 2)].flatMap(raw => {
    const info = all(first(first(raw, 19), 1), 502).find(row => first(row, 501) === 2 && first(row, 502) === 6)
    if (!info) return []
    return [{ name: first(raw, 3).toString(), guid: first(first(raw, 1), 4), index: first(first(info, 12), 501), which: first(raw, 5) }]
  })
}
const byName = buffer => Object.fromEntries(readIndices(buffer).map(row => [row.name, row.index]))
const encodeStudio = (studio, format = 'gia') => Buffer.from(studio.exportData(format).data, 'base64')

function nativeUnit(guid, name, index, slot, children = [], parent = 0) {
  const ref = cat(num(2, 1), num(3, 8), num(4, guid))
  const infos = cat(msg(502, cat(msg(11, num(501, guid)), num(501, 1), num(502, 5))),
    msg(502, cat(msg(12, num(501, index)), num(501, 2), num(502, 6))),
    parent ? Buffer.alloc(0) : msg(502, cat(msg(14, msg(501, vi(guid - 1))), num(501, 4), num(502, 4))))
  const transform = msg(13, msg(12, cat(...[0, 1, 2, 3].map(p => msg(501, cat(num(501, p), msg(502, msg(508, Buffer.alloc(0)))))))))
  const content = cat(num(501, guid), infos,
    children.length ? msg(503, cat(...children.map(vi))) : Buffer.alloc(0),
    parent ? num(504, parent) : Buffer.alloc(0),
    msg(505, msg(503, transform)), msg(505, msg(503, msg(slot, Buffer.alloc(0)))))
  return cat(msg(1, ref), ...children.map(id => msg(2, cat(num(2, 1), num(3, 8), num(4, id)))),
    str(3, name), num(5, parent ? 15 : 70), msg(19, msg(1, content)))
}
