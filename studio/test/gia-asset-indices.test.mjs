function replace(bytes, number, update) {
  return cat(...fields(bytes).map(row => {
    if (row.number !== number) return row.raw
    const value = update(row.value)
    return row.wire === 0 ? num(number, value) : msg(number, value)
  }))
}
function corruptRootIndex(bytes, rootName, index) {
  const payload = replace(bytes.subarray(20, -4), 1, raw => {
    if (first(raw, 3).toString() !== rootName) return raw
    return replace(raw, 19, ui => replace(ui, 1, content => replace(content, 502, info => {
      if (first(info, 501) !== 2 || first(info, 502) !== 6) return info
      return replace(info, 12, wrapper => replace(wrapper, 501, () => index))
    })))
  })
  return envelope(payload)
}

