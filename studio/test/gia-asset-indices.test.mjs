test('legacy type-aliased GIA is repaired on import including child records, with a migration receipt', () => {
  const bytes = legacyShop()
  const originalIndices = new Map(readIndices(bytes).map(row => [row.guid, row.index]))
  const imported = importGia(bytes)
  assert.ok(imported.warnings.some(warning => /资产编号自动迁移.*17/.test(warning)))
  const indices = {}
  walk(imported.project.root, node => { if (node.kind !== 'server-container') indices[node.guid] = node.giaInfoIndex })
  assert.equal(indices[1073741985], 13)
  assert.equal(indices[1073741993], 14)
  assert.equal(indices[1073741979], 15)
  for (let i = 0; i < 14; i++) assert.equal(indices[1073742201 + i], 16 + i)
  assert.equal(indices[1073741969], 10)
  assert.equal(indices[1073741975], 2)
  assert.equal(new Set(Object.values(indices)).size, 22)
  let changed = 0
  walk(imported.project.root, node => {
    if (originalIndices.has(node.guid) && originalIndices.get(node.guid) !== node.giaInfoIndex) changed++
  })
  assert.equal(changed, 17)
  assert.equal(imported.project.meta.giaAssetIndexSchemaVersion, 1)
  assert.equal(imported.project.meta.giaNextAssetIndex, 30)
  const studio = createStudio()
  const receipt = studio.importData('gia', bytes.toString('base64'), 'legacy-shop.gia')
  assert.ok(receipt.warnings.some(warning => /资产编号自动迁移/.test(warning)))
  for (const format of ['gia', 'gia-combined']) {
    const out = encodeStudio(studio, format)
    assert.equal(format === 'gia' ? validateGiaCompatibility(out).valid : validateServerGiaCompatibility(out).valid, true)
    const exportedIndices = new Map(readIndices(out).map(row => [row.guid, row.index]))
    for (const [guid, index] of Object.entries(indices)) assert.equal(exportedIndices.get(Number(guid)), index)
  }
  assert.equal(validateGiaCompatibility(encodeStudio(studio)).gameVersion, '7.1.0')
  assert.equal(validateServerGiaCompatibility(encodeStudio(studio, 'gia-combined')).gameVersion, '7.1.0')
  assert.equal(studio.archiveData().assets.client.meta.gameVersion, '7.0.50', 'retain imported source metadata')
})

test('old saved JSON with explicit faulty indices migrates once without rewriting GUIDs, Lua or properties', () => {
  const bytes = legacyShop()
  const seed = importGia(bytes).project
  const originalIndices = new Map(readIndices(bytes).map(row => [row.guid, row.index]))
  delete seed.meta.giaAssetIndexSchemaVersion
  // The immediately preceding build saved a high-water mark but did not repair
  // already present old numbers. Such saves must also migrate on reloading.
  seed.meta.giaNextAssetIndex = 11
  walk(seed.root, node => {
    if (!originalIndices.has(node.guid)) return
    node.giaInfoIndex = originalIndices.get(node.guid)
    delete node.giaInfoIndexSource
    if (node.kind === 'textbox') { node.text = '原有文本'; node.fontSize = 18; node.minimumFontSize = 20 }
  })
  const root = seed.root.children.find(node => node.name === '商品卡')
  const initialStudio = createStudio()
  const archive = initialStudio.archiveData()
  archive.assets.client = structuredClone(seed)
  archive.activeAssetType = 'client-control-template'
  archive.assets.scripts = [{ id: '1073742900', guid: 1073742900, path: 'shop.lua',
    source: 'local prefab = 1073741985', controlId: root.id, controlAsset: 'client-control-template' }]
  const input = JSON.stringify(archive)
  const studio = createStudio(archive)
  assert.equal(JSON.stringify(archive), input)
  assert.ok(studio.get().migrationWarnings.some(warning => /资产编号自动迁移.*17/.test(warning)))
  const corrected = studio.archiveData()
  assert.deepEqual(corrected.assets.scripts, archive.assets.scripts)
  const stripped = tree => {
    const copy = structuredClone(tree)
    walk(copy, node => { delete node.giaInfoIndex; delete node.giaInfoIndexSource })
    return copy
  }
  assert.deepEqual(stripped(corrected.assets.client.root), stripped(archive.assets.client.root))
  const fresh = createStudio(corrected)
  assert.deepEqual(fresh.archiveData(), corrected)
  assert.deepEqual(fresh.get().migrationWarnings, [])
  const target = createStudio()
  const result = target.importData('json', Buffer.from(input).toString('base64'), 'old.json')
  assert.ok(result.warnings.some(warning => /资产编号自动迁移/.test(warning)))
  const out = encodeStudio(target, 'gia-combined')
  assert.equal(validateServerGiaCompatibility(out).valid, true)
})

test('legacy repair does not renumber ambiguous alias sets or override an authored corruption', () => {
  const ambiguous = importGia(nativeLayers()).project
  delete ambiguous.meta.giaAssetIndexSchemaVersion
  walk(ambiguous.root, node => { delete node.giaInfoIndexSource })
  ambiguous.root.children[1].giaInfoIndex = 2
  // There are several distinct image numbers, unlike old type-constant exports.
  const receipt = []
  const kept = createProject(ambiguous, { warnings: receipt })
  assert.equal(kept.root.children[1].giaInfoIndex, 2)
  assert.deepEqual(receipt, [])
  assert.throws(() => exportGia(kept), /独立模板资产编号 2.*重复/)
  const corrupt = importGia(nativeLayers()).project
  corrupt.root.children[1].giaInfoIndex = 2
  corrupt.root.children[1].giaInfoIndexSource = 'authoring'
  delete corrupt.meta.giaAssetIndexSchemaVersion
  assert.throws(() => createProject(corrupt), /新建资产编号 2 重复/)
})
