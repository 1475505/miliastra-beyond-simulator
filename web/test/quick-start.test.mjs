function example() {
  const studio = createStudio()
  studio.patch({ op: 'add', kind: 'textbox', parentId: 'n1', name: 'Greeting' })
  studio.patch({ op: 'set', key: 'text', value: 'Welcome' })
  studio.patch({ op: 'selectAsset', assetType: 'client-control-template' })
  const template = studio.patch({ op: 'addTemplate', kind: 'image', name: 'ClientTemplate' })
  studio.patch({ op: 'add', kind: 'textbox', parentId: template.selectedId, name: 'ClientDetail' })
  studio.patch({ op: 'selectAsset', assetType: 'server-control-template' })
  studio.patch({ op: 'select', id: 'n1' })
  studio.patch({ op: 'addScript', controlId: 'n1', controlAsset: 'server-control-template', path: 'scripts/entry.lua',
    source: `local templateId = ${template.inspector.guid}\nfunction OnStart()\n print("guide-ready")\nend` })
  return studio.archiveData()
}
const request = (app, sessionId, action, body = {}) => fetch(`${app.url}/editor/api/${action}`, {
  method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ sessionId, ...body }),
}).then(r => r.json())

test('quick start downloads a validated example into one isolated, resumable session', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'qxqy-tutorial-'))
  const original = example()
  writeFileSync(join(directory, 'original.save.json'), JSON.stringify(original))
  const disabled = createQuickStartSource({ quickStartUrl: '', quickStartFile: 'original.save.json' })
  assert.equal(disabled.info.enabled, false, 'local file configuration cannot enable the remote example')
  await assert.rejects(() => disabled.load(), /尚未配置快速上手示例/)
  await assert.rejects(() => createQuickStartSource({ quickStartUrl: 'file:///example.save.json' }).load(), /HTTP\(S\)/)
  let bytes = '<html>download error</html>', downloads = 0
  const source = createServer((_req, res) => { downloads++; res.end(bytes) })
  await new Promise(resolve => source.listen(0, '127.0.0.1', resolve))
  const app = await createWebServer({ workspace: directory, initialPath: 'original.save.json', port: 0, maxSessions: 1,
    quickStartUrl: `http://127.0.0.1:${source.address().port}/example.save.json` })
  t.after(async () => { await app.close(); await new Promise(resolve => source.close(resolve)); rmSync(directory, { recursive: true, force: true }) })
  const call = (id, action, body) => request(app, id, action, body)
  let before = (await call('user', 'get')).value
  before = (await call('user', 'patch', { op: { op: 'renameSave', name: 'Unsaved personal work', expectedRevision: before.version } })).value
  assert.equal((await call('user', 'quick-start-open')).ok, false)
  assert.equal((await call('user', 'get')).value.save.name, 'Unsaved personal work')
  const info = (await call('user', 'quick-start-info')).value
  assert.equal(info.sourceLabel, '在线示例')
  const remote = example()
  remote.meta.name = 'Upstream example title'
  remote.scriptSync = { version: 1, workspaceDir: 'scripts', clientImportRoot: 'C:/publisher/default_import_file', clientSubdir: 'scripts' }
  bytes = JSON.stringify(remote)
  const results = await Promise.all([call('user', 'quick-start-open'), call('user', 'quick-start-open')])
  assert(results.every(result => result.ok))
  assert.equal(downloads, 2, 'one failed download plus one deduplicated retry')
  const id = results[0].value.sessionId
  assert.equal(id, results[1].value.sessionId)
  let tutorial = results[0].value.snapshot
  assert.equal(tutorial.save.name, remote.meta.name, 'the downloaded archive preserves the title from the JSON')
  assert.equal(tutorial.scriptSync, null, 'publisher machine paths are cleared in the practice copy')
  assert.deepEqual(tutorial.scripts, before.scripts, 'all inline scripts survive the download')
  assert.equal(tutorial.storage.path, '')
  assert.equal(tutorial.quickStart.originalId, 'user')
  tutorial = (await call(id, 'patch', { op: { op: 'renameSave', name: 'My lesson', expectedRevision: tutorial.version } })).value
  assert.equal(tutorial.quickStart.originalId, 'user')
  await Promise.all(Array.from({ length: 10 }, (_, i) => call(`other-${i}`, 'get')))
  assert.equal((await call('user', 'quick-start-open')).value.snapshot.save.name, 'My lesson')
  assert.equal((await call(id, 'quick-start-open')).value.sessionId, id, 'opening from the lesson does not nest copies')
  assert.deepEqual((await call('user', 'get')).value, before)
  assert.deepEqual(readdirSync(directory), ['original.save.json'], 'opening a lesson does not write files')
  assert.equal((await call(id, 'save', { path: tutorial.quickStart.savePath, expectedRevision: tutorial.version })).ok, true)
  assert.equal(JSON.parse(readFileSync(join(directory, tutorial.quickStart.savePath))).meta.name, 'My lesson')
  assert.deepEqual(JSON.parse(readFileSync(join(directory, 'original.save.json'))), original)
})

